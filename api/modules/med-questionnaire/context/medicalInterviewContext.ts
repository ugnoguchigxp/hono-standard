/**
 * 医療問診コンテキスト管理クラス
 * @description 問診システム用のコンテキスト生成と管理
 */
export class MedicalInterviewContext {
  /**
   * 初期システムプロンプトを取得
   * @returns 問診開始用のシステムプロンプト
   */
  static getInitialSystemPrompt(): string {
    return MEDICAL_INTERVIEW_SYSTEM_PROMPT;
  }

  /**
   * 問診進行状況に応じたコンテキストを生成
   * @param questionCount - 現在の質問数
   * @param collectedInfo - 収集済み情報のカテゴリ
   * @returns 進行状況に応じたコンテキスト
   */
  static getProgressContext(questionCount: number, collectedInfo: string[]): string {
    const progressContext = [];

    if (questionCount === 0) {
      progressContext.push('これが最初の質問です。挨拶と自己紹介から始めてください。');
    } else if (questionCount < 5) {
      progressContext.push('問診の序盤です。基本的な症状の詳細を確認してください。');
    } else if (questionCount < 10) {
      progressContext.push('問診の中盤です。関連症状や背景情報を収集してください。');
    } else {
      progressContext.push('問診が長時間続いています。終了の判断を検討してください。');
    }

    // 未収集の重要情報を指摘
    const importantCategories = [
      '主訴',
      '症状詳細',
      '随伴症状',
      '既往歴',
      'アレルギー',
      '服薬歴',
      '生活環境',
    ];
    const missingCategories = importantCategories.filter((cat) => !collectedInfo.includes(cat));

    if (missingCategories.length > 0) {
      progressContext.push(`まだ確認していない重要項目: ${missingCategories.join('、')}`);
    }

    return progressContext.join('\n');
  }

  /**
   * 緊急度判定用のコンテキストを取得
   * @returns 緊急度判定のためのガイドライン
   */
  static getUrgencyAssessmentContext(): string {
    return `
# 緊急度判定ガイドライン
以下の症状が報告された場合は、速やかに医療機関受診を勧めてください：

## 高緊急度（救急外来受診推奨）
- 激しい胸痛や呼吸困難
- 意識レベルの低下
- 高熱（39度以上）+ 頭痛・項部硬直
- 激しい腹痛
- 大量出血

## 中緊急度（当日受診推奨）
- 持続する発熱（38度以上）
- 激しい咳や痰
- 強い頭痛
- 嘔吐・下痢の継続

## 低緊急度（数日以内の受診推奨）
- 軽度の風邪症状
- 軽微な外傷
- 慢性的な症状の悪化
`;
  }

  /**
   * 問診終了判定用のコンテキストを取得
   * @param collectedInfo - 収集済み情報
   * @returns 終了判定のためのチェックリスト
   */
  static getCompletionCheckContext(collectedInfo: string[]): string {
    const completionItems = [
      { key: '主訴', description: '患者の主な症状' },
      { key: '症状詳細', description: 'いつから、どのような、どの程度' },
      { key: '随伴症状', description: '主症状に関連する他の症状' },
      { key: '既往歴', description: '過去の病気や治療歴' },
      { key: 'アレルギー', description: '薬物・食物アレルギー' },
      { key: '服薬歴', description: '現在服用中の薬' },
      { key: '生活環境', description: '職場環境、生活習慣' },
    ];

    const checkResults = completionItems.map((item) => {
      const collected = collectedInfo.includes(item.key);
      return `${collected ? '✓' : '○'} ${item.key}: ${item.description}`;
    });

    return `
# 問診完了チェックリスト
${checkResults.join('\n')}

✓: 収集済み
○: 未収集

未収集項目がある場合は、該当する質問を行ってください。
全項目が収集済みの場合は、問診終了を検討してください。
`;
  }
}
